package com.creedpdf.orbitalrailgun.client.render;

import com.creedpdf.orbitalrailgun.RailgunMod;
import net.minecraft.client.render.RenderLayer;
import net.minecraft.client.render.RenderPhase;
import net.minecraft.client.render.VertexFormat;
import net.minecraft.client.render.VertexFormats;
import net.minecraft.util.Identifier;

import java.util.HashMap;
import java.util.Map;

/**
 * Custom {@link RenderLayer}s for the railgun beam.
 *
 * <h2>How the glow pipeline works</h2>
 * A RenderLayer bundles the GL state ("render phases") every vertex in its buffer is drawn with.
 * Both beam layers share the parts that make energy look volumetric:
 * <ul>
 *   <li><b>Additive blending</b> ({@code LIGHTNING_TRANSPARENCY}: SRC_ALPHA, ONE). Each layer of
 *       geometry adds light to what is behind it instead of covering it, so concentric shells sum
 *       into a bright core with a soft falloff: the look of a glowing volume.</li>
 *   <li><b>No depth write</b> ({@code COLOR_MASK}). Still depth-tested (terrain hides the beam)
 *       but shells never occlude each other, so draw order doesn't matter.</li>
 *   <li><b>No culling</b>. Front and back walls of every tube are drawn; looking through a tube
 *       you see two walls at its centre and one at its rim, which reads as density.</li>
 * </ul>
 *
 * <p>{@link #GLOW} is untextured (POSITION_COLOR + the lightning shader: pure vertex colour,
 * full-bright, no fog) for smooth halos, orbs and arcs.</p>
 *
 * <p>{@link #textured(Identifier)} layers sample the beam textures generated by
 * tools/textures/build_textures.py through the vanilla beacon-beam shader (colour x texture,
 * full-bright), with bilinear filtering. The beam's V coordinate runs along its length and is
 * offset by time, so the plasma visibly streams from the muzzle to the target.</p>
 *
 * <p>Only vanilla shader programs are used, which keeps this compatible with Sodium and lets it
 * degrade gracefully under Iris shader packs. {@code RenderLayer.of} is opened by the access
 * widener; extending RenderLayer gives access to the protected phase constants.</p>
 */
public final class BeamRenderLayers extends RenderLayer {

    public static final Identifier TEX_CORE = RailgunMod.id("textures/effect/beam_core.png");
    public static final Identifier TEX_PLASMA = RailgunMod.id("textures/effect/beam_plasma.png");
    public static final Identifier TEX_HALO = RailgunMod.id("textures/effect/beam_halo.png");
    public static final Identifier TEX_HELIX = RailgunMod.id("textures/effect/beam_helix.png");
    public static final Identifier TEX_SHOCKWAVE = RailgunMod.id("textures/effect/shockwave.png");

    public static final RenderLayer GLOW = RenderLayer.of(
            "orbital_railgun_glow",
            VertexFormats.POSITION_COLOR,
            VertexFormat.DrawMode.QUADS,
            1 << 18,
            false,
            true,
            RenderLayer.MultiPhaseParameters.builder()
                    .program(LIGHTNING_PROGRAM)
                    .transparency(LIGHTNING_TRANSPARENCY)
                    .writeMaskState(COLOR_MASK)
                    .cull(DISABLE_CULLING)
                    .build(false));

    private static final Map<Identifier, RenderLayer> TEXTURED = new HashMap<>();

    public static RenderLayer textured(Identifier texture) {
        return TEXTURED.computeIfAbsent(texture, tex -> RenderLayer.of(
                "orbital_railgun_beam_" + tex.getPath(),
                VertexFormats.POSITION_COLOR_TEXTURE_LIGHT_NORMAL,
                VertexFormat.DrawMode.QUADS,
                1 << 18,
                false,
                true,
                RenderLayer.MultiPhaseParameters.builder()
                        .program(BEACON_BEAM_PROGRAM)
                        .texture(new RenderPhase.Texture(tex, true, false))
                        .transparency(LIGHTNING_TRANSPARENCY)
                        .writeMaskState(COLOR_MASK)
                        .cull(DISABLE_CULLING)
                        .build(false)));
    }

    private BeamRenderLayers(String name, VertexFormat format, VertexFormat.DrawMode mode, int bufferSize,
                             boolean crumbling, boolean translucent, Runnable setup, Runnable clear) {
        super(name, format, mode, bufferSize, crumbling, translucent, setup, clear);
        throw new UnsupportedOperationException("constants holder");
    }
}
